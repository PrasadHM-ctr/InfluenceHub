# ---------------------------------------------------------------------------
# Redis / Channel layer - graceful fallback for local development
# ---------------------------------------------------------------------------
# In production (REDIS_URL set in env) use real Redis-backed backends.
# Locally, if Redis is not running, fall back to in-process backends so
# every HTTP endpoint (including /api/login/) works without needing Redis.
def _redis_available(url: str) -> bool:
    import socket, urllib.parse
    try:
        p = urllib.parse.urlparse(url)
        with socket.create_connection((p.hostname or "127.0.0.1", p.port or 6379), timeout=0.5):
            return True
    except OSError:
        return False


_use_redis = bool(os.getenv("REDIS_URL")) or _redis_available(REDIS_URL)

